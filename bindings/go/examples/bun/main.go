// This example uses the Go Bun ORM with the native DecentDB database/sql driver.
package main

import (
	"bytes"
	"context"
	"database/sql"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"net/url"
	"os"
	"path/filepath"
	"time"

	decentdb "github.com/sphildreth/decentdb/bindings/go/decentdb-go"
	"github.com/uptrace/bun"
	"github.com/uptrace/bun/dialect/pgdialect"
)

type Customer struct {
	bun.BaseModel `bun:"table:bun_customers,alias:customer"`
	ID            int64      `bun:",pk,autoincrement"`
	Email         string     `bun:",unique,notnull"`
	Name          string     `bun:",notnull"`
	Invoices      []*Invoice `bun:"rel:has-many,join:id=customer_id"`
}

type Invoice struct {
	bun.BaseModel `bun:"table:bun_invoices,alias:invoice"`
	ID            int64            `bun:",pk,autoincrement"`
	Number        string           `bun:",unique,notnull"`
	CustomerID    int64            `bun:",notnull"`
	Amount        decentdb.Decimal `bun:",notnull,type:NUMERIC"`
	Paid          bool             `bun:",notnull"`
	IssuedAt      time.Time        `bun:",notnull,type:TIMESTAMPTZ"`
	CreatedAt     time.Time        `bun:",notnull,default:CURRENT_TIMESTAMP"`
	Metadata      json.RawMessage  `bun:",notnull"`
	Receipt       []byte
	Note          *string
	Customer      *Customer `bun:"rel:belongs-to,join:customer_id=id"`
}

var issuedAt = time.Date(2024, 4, 1, 0, 0, 0, 123456000, time.UTC)

func main() {
	dbPath := flag.String("db", "../../../../.tmp/bun-orm/demo.ddb", "database file, or :memory:")
	verbose := flag.Bool("verbose", false, "print the SQL generated by Bun")
	flag.Parse()
	if err := run(context.Background(), *dbPath, *verbose, os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, "Bun + DecentDB:", err)
		os.Exit(1)
	}
}

func openDB(ctx context.Context, path string, verbose bool) (*bun.DB, error) {
	dsn := path
	if path != ":memory:" {
		absolute, err := filepath.Abs(path)
		if err != nil {
			return nil, err
		}
		if err := os.MkdirAll(filepath.Dir(absolute), 0755); err != nil {
			return nil, err
		}
		dsn = (&url.URL{Scheme: "file", Path: absolute}).String()
	}
	sqldb, err := sql.Open("decentdb", dsn)
	if err != nil {
		return nil, err
	}
	// Keep one native connection for this single-writer example. In particular,
	// each :memory: connection would otherwise contain a different database.
	sqldb.SetMaxOpenConns(1)
	sqldb.SetMaxIdleConns(1)
	if err := sqldb.PingContext(ctx); err != nil {
		sqldb.Close()
		return nil, err
	}
	db := bun.NewDB(sqldb, pgdialect.New())
	if verbose {
		db.AddQueryHook(sqlLogger{})
	}
	return db, nil
}

func run(ctx context.Context, path string, verbose bool, out io.Writer) error {
	db, err := openDB(ctx, path, verbose)
	if err != nil {
		return fmt.Errorf("open database: %w", err)
	}
	fmt.Fprintf(out, "DecentDB %s + Bun %s\n", decentdb.EngineVersion(), bun.Version())
	id, demoErr := showcase(ctx, db, out)
	if err := errors.Join(demoErr, db.Close()); err != nil {
		return err
	}
	if path == ":memory:" {
		return nil
	}

	// Reopen the file through Bun to demonstrate persistence after closing the
	// native handle. No separate database service is involved.
	reopened, err := openDB(ctx, path, verbose)
	if err != nil {
		return fmt.Errorf("reopen database: %w", err)
	}
	var invoice Invoice
	err = reopened.NewSelect().Model(&invoice).Where("invoice.id = ?", id).Scan(ctx)
	if err == nil && (invoice.Amount != (decentdb.Decimal{Unscaled: 20}) || !invoice.Paid) {
		err = errors.New("reopened invoice did not retain its committed values")
	}
	if err := errors.Join(err, reopened.Close()); err != nil {
		return fmt.Errorf("verify persistence: %w", err)
	}
	fmt.Fprintf(out, "Reopened %s: invoice %s, amount %s, paid=%t\n", path, invoice.Number, invoice.Amount, invoice.Paid)
	return nil
}

func showcase(ctx context.Context, db *bun.DB, out io.Writer) (int64, error) {
	if err := createSchema(ctx, db); err != nil {
		return 0, fmt.Errorf("create schema: %w", err)
	}
	invoice, err := seed(ctx, db)
	if err != nil {
		return 0, fmt.Errorf("seed transaction: %w", err)
	}
	if invoice.ID <= 0 || invoice.CustomerID <= 0 {
		return 0, errors.New("INSERT RETURNING did not populate generated IDs")
	}
	fmt.Fprintf(out, "Transaction + upserts: customer ID %d, invoice ID %d\n", invoice.CustomerID, invoice.ID)

	// Native Decimal implements Scanner and Valuer for ORM integration.
	_, err = db.NewUpdate().Model(invoice).
		Set("amount = amount + ?", decentdb.Decimal{Unscaled: 1, Scale: 2}).
		Set("paid = ?", true).WherePK().Returning("amount, paid").Exec(ctx)
	if err != nil {
		return 0, fmt.Errorf("update invoice: %w", err)
	}
	if invoice.Amount != (decentdb.Decimal{Unscaled: 20}) || !invoice.Paid {
		return 0, errors.New("UPDATE RETURNING did not produce exactly 20.00")
	}
	fmt.Fprintf(out, "Exact NUMERIC update + RETURNING: 19.99 + 0.01 = %s\n", invoice.Amount)

	if err := demonstrateRollback(ctx, db, invoice.ID); err != nil {
		return 0, err
	}
	fmt.Fprintln(out, "Rollback: attempted amount change was discarded")

	// Bun loads a belongs-to relation using a JOIN and scans both models.
	var loaded Invoice
	if err := db.NewSelect().Model(&loaded).Relation("Customer").
		Where("invoice.id = ?", invoice.ID).Scan(ctx); err != nil {
		return 0, fmt.Errorf("load relation: %w", err)
	}
	if loaded.Customer == nil || loaded.Customer.ID != invoice.CustomerID || !loaded.IssuedAt.Equal(issuedAt) || loaded.CreatedAt.IsZero() || !bytes.Equal(loaded.Receipt, []byte{0, 1, 255}) || loaded.Note != nil {
		return 0, errors.New("relation or microsecond TIMESTAMPTZ round trip failed")
	}
	fmt.Fprintf(out, "Relation: %s belongs to %s; issued %s\n", loaded.Number, loaded.Customer.Name, loaded.IssuedAt.Format(time.RFC3339Nano))

	count, err := db.NewSelect().Model((*Invoice)(nil)).
		Where("invoice.customer_id = ?", invoice.CustomerID).
		Where("invoice.metadata ->> 'department' = ?", "engineering").Count(ctx)
	if err != nil {
		return 0, fmt.Errorf("JSON filter: %w", err)
	}
	if count != 1 {
		return 0, fmt.Errorf("JSON filter: expected one invoice, got %d", count)
	}
	fmt.Fprintf(out, "Indexed customer lookup + JSON text extraction: %d invoice\n", count)

	var decimalType, timestampType string
	if err := db.NewRaw("SELECT PG_TYPEOF(CAST('0.1' AS NUMERIC)), PG_TYPEOF(TO_TIMESTAMP(?))", 1711929600).
		Scan(ctx, &decimalType, &timestampType); err != nil {
		return 0, fmt.Errorf("type inspection: %w", err)
	}
	if decimalType != "numeric" || timestampType != "timestamp with time zone" {
		return 0, errors.New("unexpected SQL type names")
	}
	fmt.Fprintf(out, "SQL types: %s; %s\n", decimalType, timestampType)

	// Exercise ORM DELETE on a disposable draft, within a transaction so a
	// failed delete does not leave an extra invoice behind.
	err = db.RunInTx(ctx, nil, func(ctx context.Context, tx bun.Tx) error {
		draft := &Invoice{Number: "BUN-DRAFT", CustomerID: invoice.CustomerID, Amount: decentdb.Decimal{Unscaled: 1}, IssuedAt: issuedAt, Metadata: json.RawMessage(`{}`)}
		if _, err := tx.NewInsert().Model(draft).Exec(ctx); err != nil {
			return err
		}
		result, err := tx.NewDelete().Model(draft).WherePK().Returning("id").Exec(ctx)
		if err != nil {
			return err
		}
		affected, err := result.RowsAffected()
		if err == nil && affected != 1 {
			return fmt.Errorf("draft delete affected %d rows", affected)
		}
		return err
	})
	if err != nil {
		return 0, fmt.Errorf("draft insert/delete: %w", err)
	}
	fmt.Fprintln(out, "ORM delete + RETURNING: disposable draft removed")
	if err := demonstrateCollections(ctx, db, invoice.CustomerID, out); err != nil {
		return 0, err
	}
	if err := demonstrateSoftDelete(ctx, db, out); err != nil {
		return 0, err
	}
	if err := demonstrateMigrations(ctx, db, out); err != nil {
		return 0, err
	}
	return invoice.ID, nil
}

func createSchema(ctx context.Context, db *bun.DB) error {
	if _, err := db.NewCreateTable().Model((*Customer)(nil)).IfNotExists().Exec(ctx); err != nil {
		return err
	}
	if _, err := db.NewCreateTable().Model((*Invoice)(nil)).WithForeignKeys().IfNotExists().Exec(ctx); err != nil {
		return err
	}
	_, err := db.NewCreateIndex().Model((*Invoice)(nil)).
		Index("bun_invoices_customer_idx").Column("customer_id").IfNotExists().Exec(ctx)
	return err
}

func seed(ctx context.Context, db *bun.DB) (*Invoice, error) {
	customer := &Customer{Email: "ada@example.test", Name: "Ada O'Neil"}
	invoice := &Invoice{Number: "BUN-001", Amount: decentdb.Decimal{Unscaled: 1999, Scale: 2}, IssuedAt: issuedAt,
		Metadata: json.RawMessage(`{"department":"engineering","priority":2}`), Receipt: []byte{0, 1, 255}}
	err := db.RunInTx(ctx, nil, func(ctx context.Context, tx bun.Tx) error {
		if _, err := tx.NewInsert().Model(customer).
			On("CONFLICT (email) DO UPDATE").Set("name = EXCLUDED.name").Returning("id").Exec(ctx); err != nil {
			return err
		}
		invoice.CustomerID = customer.ID
		_, err := tx.NewInsert().Model(invoice).
			On("CONFLICT (number) DO UPDATE").
			Set("customer_id = EXCLUDED.customer_id").Set("amount = EXCLUDED.amount").
			Set("paid = EXCLUDED.paid").Set("issued_at = EXCLUDED.issued_at").
			Set("metadata = EXCLUDED.metadata").Returning("id").Exec(ctx)
		return err
	})
	return invoice, err
}

func demonstrateRollback(ctx context.Context, db *bun.DB, invoiceID int64) error {
	rollback := errors.New("intentional demo rollback")
	err := db.RunInTx(ctx, nil, func(ctx context.Context, tx bun.Tx) error {
		if _, err := tx.NewUpdate().Model((*Invoice)(nil)).Set("amount = ?", decentdb.Decimal{Unscaled: 999}).
			Where("id = ?", invoiceID).Exec(ctx); err != nil {
			return err
		}
		return rollback
	})
	if !errors.Is(err, rollback) {
		return fmt.Errorf("rollback transaction: %w", err)
	}
	var invoice Invoice
	if err := db.NewSelect().Model(&invoice).Where("invoice.id = ?", invoiceID).Scan(ctx); err != nil {
		return err
	}
	if invoice.Amount != (decentdb.Decimal{Unscaled: 20}) {
		return errors.New("rollback did not preserve the committed amount")
	}
	return nil
}

type sqlLogger struct{}

func (sqlLogger) BeforeQuery(ctx context.Context, _ *bun.QueryEvent) context.Context { return ctx }

func (sqlLogger) AfterQuery(_ context.Context, event *bun.QueryEvent) {
	fmt.Fprintln(os.Stderr, "SQL:", event.Query)
	if event.Err != nil {
		fmt.Fprintln(os.Stderr, "SQL error:", event.Err)
	}
}
